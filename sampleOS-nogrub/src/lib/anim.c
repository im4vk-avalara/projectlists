static inline i32 sin8(u8 angle)
{
    return sin_lut[angle];
}

static fb_color_t palette[256];

static void build_palette(void)
{
    for (int i = 0; i < 256; i++) {
        i32 r = sin8((u8)(i * 1));
        i32 g = sin8((u8)(i * 1 + 85));
        i32 b = sin8((u8)(i * 1 + 170));

        palette[i].r = (u8)(((r + 127) * 63) / 254);
        palette[i].g = (u8)(((g + 127) * 63) / 254);
        palette[i].b = (u8)(((b + 127) * 63) / 254);
    }
}

static void compute_plasma(void)
{
    u8 *fb = (u8 *)0xA0000;

    for (u32 y = 0; y < FB_HEIGHT; y++) {
        for (u32 x = 0; x < FB_WIDTH; x++) {
            i32 v = sin8((u8)(x * 4))
                  + sin8((u8)(y * 4))
                  + sin8((u8)((x + y) * 3))
                  + sin8((u8)((x * x + y * y) >> 4));
            fb[y * FB_WIDTH + x] = (u8)(v + 512);
        }
    }
}

static void delay(u32 loops)
{
    for (volatile u32 i = 0; i < loops; i++) {
        __asm__ volatile ("nop");
    }
}

void plasma_init(void)
{
    build_palette();
    fb_set_palette(palette, 256);
    compute_plasma();
}

void plasma_run_forever(void)
{
    u8 shift = 0;

    while (1) {
        outb(0x3C8, 0);
        for (u32 i = 0; i < 256; i++) {
            u32 idx = (i + shift) & 0xFF;
            outb(0x3C9, palette[idx].r & 0x3F);
            outb(0x3C9, palette[idx].g & 0x3F);
            outb(0x3C9, palette[idx].b & 0x3F);
        }

        shift++;
        delay(50000000);
    }
}
