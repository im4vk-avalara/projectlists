"""
ToyLang C Code Generator - Generates C code from AST

This is part of the seed compiler (Stage 0) written in Python.
It generates portable C code from the ToyLang AST.

Educational notes:
- Code generation is the final phase of compilation
- We translate AST nodes to equivalent C code
- The generated C is then compiled by gcc/clang
- We use int64_t for all values for consistency
"""

from typing import List, Set
from ast_nodes import *


class CodeGenerator(ASTVisitor):
    """
    C code generator for ToyLang.
    
    Generates readable, portable C code that can be compiled with gcc/clang.
    
    Design decisions:
    - All values are int64_t (64-bit signed integers)
    - Functions map directly to C functions
    - Control flow maps directly to C control flow
    - print() becomes printf calls
    
    Usage:
        gen = CodeGenerator()
        c_code = gen.generate(ast)
    """
    
    def __init__(self):
        self.output: List[str] = []
        self.indent_level = 0
        self.string_literals: List[str] = []
    
    def emit(self, text: str = ""):
        """Emit a line of code with current indentation"""
        if text:
            self.output.append("    " * self.indent_level + text)
        else:
            self.output.append("")
    
    def emit_raw(self, text: str):
        """Emit text without indentation (for inline expressions)"""
        self.output.append(text)
    
    def indent(self):
        """Increase indentation"""
        self.indent_level += 1
    
    def dedent(self):
        """Decrease indentation"""
        self.indent_level -= 1
    
    def generate(self, program: Program) -> str:
        """
        Generate C code for the entire program.
        
        Returns:
            Complete C source code as a string
        """
        self.output = []
        self.string_literals = []
        
        # Emit header
        self.emit("/* Generated by ToyLang Compiler */")
        self.emit("#include <stdio.h>")
        self.emit("#include <stdint.h>")
        self.emit("#include <stdlib.h>")
        self.emit()
        
        # Emit built-in function wrappers
        self.emit("/* Built-in functions */")
        self.emit("static int64_t toy_putchar(int64_t c) {")
        self.indent()
        self.emit("putchar((int)c);")
        self.emit("return 0;")
        self.dedent()
        self.emit("}")
        self.emit()
        self.emit("static int64_t toy_getchar(void) {")
        self.indent()
        self.emit("return getchar();")
        self.dedent()
        self.emit("}")
        self.emit()
        
        # Forward declarations for all functions
        self.emit("/* Forward declarations */")
        for func in program.functions:
            params = ", ".join(["int64_t " + p for p in func.params])
            if not params:
                params = "void"
            self.emit(f"int64_t fn_{func.name}({params});")
        self.emit()
        
        # Generate each function
        for func in program.functions:
            self.visit(func)
            self.emit()
        
        # Generate main entry point
        self.emit("/* Entry point */")
        self.emit("int main(void) {")
        self.indent()
        self.emit("return (int)fn_main();")
        self.dedent()
        self.emit("}")
        
        return "\n".join(self.output)
    
    def visit_Function(self, node: Function):
        """Generate C function"""
        params = ", ".join(["int64_t " + p for p in node.params])
        if not params:
            params = "void"
        
        self.emit(f"int64_t fn_{node.name}({params}) {{")
        self.indent()
        
        # Generate body statements
        for stmt in node.body.statements:
            self.visit(stmt)
        
        # Ensure function returns (default return 0)
        self.emit("return 0;")
        
        self.dedent()
        self.emit("}")
    
    def visit_Block(self, node: Block):
        """Generate block (just emit statements, no braces for inner blocks)"""
        for stmt in node.statements:
            self.visit(stmt)
    
    def visit_LetStmt(self, node: LetStmt):
        """Generate variable declaration"""
        init_expr = self.expr_to_string(node.init)
        self.emit(f"int64_t {node.name} = {init_expr};")
    
    def visit_AssignStmt(self, node: AssignStmt):
        """Generate assignment"""
        value_expr = self.expr_to_string(node.value)
        self.emit(f"{node.name} = {value_expr};")
    
    def visit_IfStmt(self, node: IfStmt):
        """Generate if statement"""
        cond_expr = self.expr_to_string(node.condition)
        self.emit(f"if ({cond_expr}) {{")
        self.indent()
        for stmt in node.then_block.statements:
            self.visit(stmt)
        self.dedent()
        
        if node.else_block:
            self.emit("} else {")
            self.indent()
            for stmt in node.else_block.statements:
                self.visit(stmt)
            self.dedent()
        
        self.emit("}")
    
    def visit_WhileStmt(self, node: WhileStmt):
        """Generate while loop"""
        cond_expr = self.expr_to_string(node.condition)
        self.emit(f"while ({cond_expr}) {{")
        self.indent()
        for stmt in node.body.statements:
            self.visit(stmt)
        self.dedent()
        self.emit("}")
    
    def visit_ReturnStmt(self, node: ReturnStmt):
        """Generate return statement"""
        if node.value:
            value_expr = self.expr_to_string(node.value)
            self.emit(f"return {value_expr};")
        else:
            self.emit("return 0;")
    
    def visit_PrintStmt(self, node: PrintStmt):
        """Generate print statement as printf calls"""
        # Build format string and arguments
        format_parts = []
        args = []
        
        for i, arg in enumerate(node.args):
            if i > 0:
                format_parts.append(" ")  # Space between arguments
            
            if isinstance(arg, StringLiteral):
                # String literal: embed in format
                format_parts.append(self.escape_c_string(arg.value))
            else:
                # Expression: use %lld format
                format_parts.append("%lld")
                args.append(self.expr_to_string(arg))
        
        format_parts.append("\\n")  # Newline at end
        
        format_str = "".join(format_parts)
        if args:
            args_str = ", " + ", ".join(f"(long long)({a})" for a in args)
        else:
            args_str = ""
        
        self.emit(f'printf("{format_str}"{args_str});')
    
    def visit_ExprStmt(self, node: ExprStmt):
        """Generate expression statement"""
        expr_str = self.expr_to_string(node.expr)
        self.emit(f"{expr_str};")
    
    # ============ Expression generation ============
    
    def expr_to_string(self, node: ASTNode) -> str:
        """Convert expression AST to C expression string"""
        if isinstance(node, IntLiteral):
            return f"((int64_t){node.value})"
        
        if isinstance(node, BoolLiteral):
            return "1" if node.value else "0"
        
        if isinstance(node, StringLiteral):
            # String literals in expressions - not supported in ToyLang0
            raise ValueError("String literals not supported in expressions")
        
        if isinstance(node, Identifier):
            return node.name
        
        if isinstance(node, BinaryExpr):
            left = self.expr_to_string(node.left)
            right = self.expr_to_string(node.right)
            op = self.binary_op_to_c(node.op)
            
            # Handle logical operators specially for proper C behavior
            if node.op in (BinaryOp.AND, BinaryOp.OR):
                return f"(({left}) {op} ({right}) ? 1 : 0)"
            
            return f"(({left}) {op} ({right}))"
        
        if isinstance(node, UnaryExpr):
            operand = self.expr_to_string(node.operand)
            op = self.unary_op_to_c(node.op)
            if node.op == UnaryOp.NOT:
                return f"(({operand}) ? 0 : 1)"
            return f"({op}({operand}))"
        
        if isinstance(node, CallExpr):
            args = ", ".join(self.expr_to_string(arg) for arg in node.args)
            
            # Map to built-in functions
            if node.callee == 'putchar':
                return f"toy_putchar({args})"
            if node.callee == 'getchar':
                return "toy_getchar()"
            
            return f"fn_{node.callee}({args})"
        
        raise ValueError(f"Unknown expression type: {type(node).__name__}")
    
    def binary_op_to_c(self, op: BinaryOp) -> str:
        """Convert binary operator to C operator"""
        mapping = {
            BinaryOp.ADD: '+',
            BinaryOp.SUB: '-',
            BinaryOp.MUL: '*',
            BinaryOp.DIV: '/',
            BinaryOp.MOD: '%',
            BinaryOp.EQ: '==',
            BinaryOp.NE: '!=',
            BinaryOp.LT: '<',
            BinaryOp.GT: '>',
            BinaryOp.LE: '<=',
            BinaryOp.GE: '>=',
            BinaryOp.AND: '&&',
            BinaryOp.OR: '||',
        }
        return mapping[op]
    
    def unary_op_to_c(self, op: UnaryOp) -> str:
        """Convert unary operator to C operator"""
        mapping = {
            UnaryOp.NEG: '-',
            UnaryOp.NOT: '!',
        }
        return mapping[op]
    
    def escape_c_string(self, s: str) -> str:
        """Escape a string for C"""
        result = []
        for ch in s:
            if ch == '\n':
                result.append('\\n')
            elif ch == '\t':
                result.append('\\t')
            elif ch == '"':
                result.append('\\"')
            elif ch == '\\':
                result.append('\\\\')
            elif ord(ch) < 32 or ord(ch) > 126:
                result.append(f'\\x{ord(ch):02x}')
            else:
                result.append(ch)
        return ''.join(result)


def generate(program: Program) -> str:
    """
    Convenience function to generate C code from AST.
    
    Returns:
        C source code as a string
    """
    gen = CodeGenerator()
    return gen.generate(program)


